// Build-time: content/lesson-plan.md -> src/content/guide-content.ts
// Run: node scripts/build-guide.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Marked } from "marked";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// The "시각 자료 제작 목록 (Code 전달용)" section is an internal production list, not lesson content → excluded.
const src = readFileSync(resolve(root, "content/lesson-plan.md"), "utf8")
  .replace(/^## 시각 자료 제작 목록[^\n]*\n[\s\S]*?(?=^## )/m, "");

// alias -> predicate on heading text (each alias used once, document order)
const ALIAS_RULES = [
  ["overview", (t) => t.startsWith("연수 개요")],
  ["period-1", (t) => t.startsWith("1교시 (가)")],
  ["terms", (t) => t.startsWith("1교시 (나) ")],
  ["quiz-app", (t) => t.startsWith("1교시 (나+)")],
  ["period-2", (t) => t.startsWith("2교시 (다) ")],
  ["chatgpt-work", (t) => t.startsWith("2교시 (다-1)")],
  ["chatgpt-sites", (t) => t.startsWith("2교시 (다-2)")],
  ["skills", (t) => t.startsWith("2교시 (라) ")],
  ["skills-mcp-practice", (t) => t.startsWith("2교시 (라-1)")],
  ["mcp", (t) => t.startsWith("① 플러그인 설치")],
  ["skill-create", (t) => t.startsWith("② 스킬 만들기")],
  ["recommended", (t) => t.startsWith("2교시 (라-2)")],
  ["matching-activity", (t) => t.startsWith("활동:")],
  ["high-school", (t) => t.startsWith("고등학생과 LLM")],
  ["period-3", (t) => t.startsWith("3교시 실습")],
  ["practice-steps", (t) => t.startsWith("3교시 실습")],
  ["step-1", (t) => t.startsWith("1단계")],
  ["step-2", (t) => t.startsWith("2단계")],
  ["step-3", (t) => t.startsWith("3단계")],
  ["extras", (t) => t.startsWith("그 외 제안")],
  ["copilot", (t) => t.startsWith("부록: Microsoft Copilot")],
  ["copilot-chat", (t) => t.startsWith("① Copilot Chat")],
  ["copilot-notebooks", (t) => t.startsWith("② 전자 필기장")],
  ["visual-assets", (t) => t.startsWith("시각 자료 제작")],
  ["sources", (t) => t === "출처"],
];

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const decode = (s) => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, "&");
const slugify = (t) =>
  t.toLowerCase().normalize("NFC").replace(/[^\p{L}\p{N}\s-]/gu, "").trim().replace(/\s+/g, "-").replace(/-+/g, "-") || "section";

const seen = new Map();
const usedAlias = new Set();
const toc = [];
const aliases = {};
const rawHtmlFound = [];

const marked = new Marked({ gfm: true });
marked.use({
  renderer: {
    html({ text }) { rawHtmlFound.push(text.trim().slice(0, 60)); return esc(text); },
    heading({ tokens, depth }) {
      const inner = this.parser.parseInline(tokens);
      const text = decode(inner.replace(/<[^>]+>/g, "")).trim();
      if (depth > 3) return `<h${depth}>${inner}</h${depth}>\n`;
      if (depth === 1) return `<h2>${inner}</h2>\n`;
      let id = slugify(text);
      const n = (seen.get(id) ?? 0) + 1; seen.set(id, n);
      if (n > 1) id = `${id}-${n}`;
      let spans = "";
      for (const [alias, test] of ALIAS_RULES) {
        if (!usedAlias.has(alias) && test(text)) { usedAlias.add(alias); aliases[alias] = id; spans += `<span id="${alias}"></span>`; }
      }
      toc.push({ id, text, level: depth });
      return `${spans}<h${depth} id="${id}">${inner}</h${depth}>\n`;
    },
    link({ href, title, tokens }) {
      const inner = this.parser.parseInline(tokens);
      if (/^\s*(javascript|data|vbscript):/i.test(href)) return inner;
      const ext = /^https?:/i.test(href);
      return `<a href="${esc(href)}"${title ? ` title="${esc(title)}"` : ""}${ext ? ' target="_blank" rel="noopener noreferrer"' : ""}>${inner}</a>`;
    },
    image({ text }) { return `<span class="guide-img-alt">[그림: ${esc(text)}]</span>`; },
  },
});

// Drop the document title line (page supplies its own h1); body text untouched.
const body = src.replace(/^# .*\n/, "");
let html = marked.parse(body);
html = html.replace(/\s+style="[^"]*"/gi, "");
// a11y: markdown task-list boxes are static text here, not form controls; header cells get scope
html = html.replace(/<input checked="" disabled="" type="checkbox">/g, '<span aria-hidden="true">☑</span><span class="sr-only">완료 항목:</span>')
           .replace(/<input disabled="" type="checkbox">/g, '<span aria-hidden="true">☐</span><span class="sr-only">점검 항목:</span>')
           .replace(/<th(\s|>)/g, '<th scope="col"$1')
           .replace(/<th scope="col"><\/th>/g, '<th scope="col"><span class="sr-only">구분</span></th>');

// 참가자용 가이드에서 강사용 운영 내용은 접어 둔다 (교사 리뷰 2026-11-26)
html = html.replace(/(<h2 id="그-외-제안">[^<]*<\/h2>)([\s\S]*?)(?=<span id=|$)/, (_m, h, rest) => `${h}<details class="ops-tips"><summary>강사·운영자용 운영 팁 (참가자는 건너뛰어도 돼요)</summary>${rest}</details>`);
html = html.replace(/<p>(연수 운영 팁:[\s\S]*?)<\/p>/, (_m, t) => `<details class="ops-tips"><summary>강사용 운영 팁</summary><p>${t}</p></details>`);

const out = `// GENERATED by scripts/build-guide.mjs from content/lesson-plan.md. Do not edit.
export const GUIDE_HTML: string = ${JSON.stringify(html)};
export const GUIDE_TOC: { id: string; text: string; level: 2 | 3 }[] = ${JSON.stringify(toc)};
export const GUIDE_ALIASES: Record<string, string> = ${JSON.stringify(aliases)};
`;
mkdirSync(resolve(root, "src/content"), { recursive: true });
writeFileSync(resolve(root, "src/content/guide-content.ts"), out);
console.log(`guide: ${toc.length} toc entries, ${Object.keys(aliases).length} aliases, ${rawHtmlFound.length} raw html chunks escaped`);
for (const [a] of ALIAS_RULES) if (!usedAlias.has(a)) console.warn("unused alias:", a);
for (const r of rawHtmlFound) console.log("raw html:", r);
console.log(JSON.stringify(aliases));
